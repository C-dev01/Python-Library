
# ARITHMETIC OPERATORS
x = 5
y = 10

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y)
print(x ** y)

#COMPARISION OPERATORS
print(x == y)
print(x != y)
print(x <= y)
print(x >= y)
print(x < y)
print(x > y)

#LOGICAL OPERATORS
print(x < y and  x > y)
print(x < y or  x > y)
print(not(x > y))

#ASSIGNMENT OPERATOR
a = 2
b = 3

a = a+6
a += 6

a = a-3
a -= 3

b = b/1
b /= 1

b = b*3
b *= 3



