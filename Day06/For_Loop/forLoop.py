# for loop is used to iterate sequences like lists, tuples, or strings.

# for loop in list
foodList = ["Pizza", "Pasta", "Samosa"]
for item in foodList:
    print(item)


# for loop in tuple
collegeTuple = ("NIT-Trichy", "NIT-Wrangal", "BITS Mesra")
for eachItem in collegeTuple:
    print("Chanchal wants this college in 2026 :",eachItem)

    

